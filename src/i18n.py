def current_language():
    forced = os.getenv('RYOKU_PROXY_LANG', '').strip().lower()
    if forced in ('en', 'ru'):
        return forced
    # Use the system's locale, not only the window manager's preferred UI theme.
    env = os.environ.get('LC_ALL') or os.environ.get('LC_MESSAGES') or os.environ.get('LANGUAGE') or os.environ.get('LANG', '')
    if env.lower().startswith('ru'):
        return 'ru'
    try:
        return 'ru' if (locale.getlocale()[0] or '').lower().startswith('ru') else 'en'
    except (ValueError, TypeError):
        return 'en'


LANG = current_language()


def tr(key):
    entry = LANGUAGES.get(key)
    if entry is None:
        raise KeyError('Missing UI translation: ' + key)
    return entry[1] if LANG == 'ru' else entry[0]

